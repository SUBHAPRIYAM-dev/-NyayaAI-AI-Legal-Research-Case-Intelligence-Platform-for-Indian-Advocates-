import * as React from "react";
import { cn } from "@/lib/utils";

export const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { hoverEffect?: boolean }
>(({ className, hoverEffect = false, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-lg border border-slate-800 bg-navy-900/80 text-slate-100 shadow-sm backdrop-blur-sm transition-all duration-200",
      hoverEffect && "terminal-border-hover hover:translate-y-[-1px]",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

